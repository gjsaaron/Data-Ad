-- Audit table
CREATE TABLE IF NOT EXISTS borrow_items_audit (
    audit_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    borrow_item_id INTEGER,
    borrow_id      INTEGER,
    equipment_id   INTEGER,
    old_quantity   INTEGER,
    new_quantity   INTEGER,
    operation      VARCHAR(10) NOT NULL CHECK (operation IN ('INSERT','UPDATE','DELETE')),
    changed_at     TIMESTAMP  NOT NULL DEFAULT NOW()
);


-- ── BEFORE trigger: validate quantity against available stock ──────────────
CREATE OR REPLACE FUNCTION fn_validate_borrow_quantity()
RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_owned INTEGER;
    v_out   INTEGER;
    v_avail INTEGER;
BEGIN
    SELECT quantity_available INTO v_owned
    FROM   equipment
    WHERE  equipment_id = NEW.equipment_id;

    -- Get current units out
    v_out := fn_total_borrowed(NEW.equipment_id);

    -- On UPDATE, the OLD quantity is being replaced, so subtract it from units_out
    IF TG_OP = 'UPDATE' THEN
        v_out := v_out - OLD.quantity;
    END IF;

    v_avail := v_owned - v_out;

    IF NEW.quantity > v_avail THEN
        RAISE EXCEPTION
            'Stock exceeded: requested %, only % available for equipment_id %.',
            NEW.quantity, v_avail, NEW.equipment_id;
    END IF;

    RETURN NEW;  -- allow the operation to proceed
END;
$$;

CREATE OR REPLACE TRIGGER trg_validate_borrow_quantity
BEFORE INSERT OR UPDATE ON borrow_items
FOR EACH ROW EXECUTE FUNCTION fn_validate_borrow_quantity();


-- ── AFTER trigger: write to audit log ─────────────────────────────────────
CREATE OR REPLACE FUNCTION fn_borrow_items_audit()
RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO borrow_items_audit
            (borrow_item_id, borrow_id, equipment_id, old_quantity, new_quantity, operation)
        VALUES (NEW.borrow_item_id, NEW.borrow_id, NEW.equipment_id,
                NULL, NEW.quantity, 'INSERT');

    ELSIF TG_OP = 'UPDATE' THEN
        INSERT INTO borrow_items_audit
            (borrow_item_id, borrow_id, equipment_id, old_quantity, new_quantity, operation)
        VALUES (NEW.borrow_item_id, NEW.borrow_id, NEW.equipment_id,
                OLD.quantity, NEW.quantity, 'UPDATE');

    ELSIF TG_OP = 'DELETE' THEN
        INSERT INTO borrow_items_audit
            (borrow_item_id, borrow_id, equipment_id, old_quantity, new_quantity, operation)
        VALUES (OLD.borrow_item_id, OLD.borrow_id, OLD.equipment_id,
                OLD.quantity, NULL, 'DELETE');
    END IF;

    RETURN NULL;  -- AFTER trigger: return value is ignored
END;
$$;

CREATE OR REPLACE TRIGGER trg_borrow_items_audit
AFTER INSERT OR UPDATE OR DELETE ON borrow_items
FOR EACH ROW EXECUTE FUNCTION fn_borrow_items_audit();
