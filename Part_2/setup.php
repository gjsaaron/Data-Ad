        CREATE TABLE IF NOT EXISTS borrowers (
            borrower_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            borrower_no   VARCHAR(20)  NOT NULL UNIQUE,
            full_name     VARCHAR(120) NOT NULL,
            borrower_type VARCHAR(30)  NOT NULL
                CHECK (borrower_type IN ('Student','Faculty','Staff'))
        );
        CREATE TABLE IF NOT EXISTS equipment (
            equipment_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            property_no        VARCHAR(30)  NOT NULL UNIQUE,
            equipment_name     VARCHAR(120) NOT NULL,
            quantity_available INTEGER      NOT NULL DEFAULT 0
                CHECK (quantity_available >= 0)
        );
        CREATE TABLE IF NOT EXISTS borrow_transactions (
            borrow_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            borrower_id INTEGER NOT NULL,
            borrow_date DATE    NOT NULL,
            due_date    DATE    NOT NULL,
            status      VARCHAR(20) NOT NULL
                CHECK (status IN ('Borrowed','Returned','Overdue','Cancelled')),
            FOREIGN KEY (borrower_id) REFERENCES borrowers(borrower_id),
            CHECK (due_date >= borrow_date)
        );
        CREATE TABLE IF NOT EXISTS borrow_items (
            borrow_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            borrow_id      INTEGER NOT NULL,
            equipment_id   INTEGER NOT NULL,
            quantity       INTEGER NOT NULL CHECK (quantity > 0),
            FOREIGN KEY (borrow_id)    REFERENCES borrow_transactions(borrow_id) ON DELETE CASCADE,
            FOREIGN KEY (equipment_id) REFERENCES equipment(equipment_id),
            UNIQUE (borrow_id, equipment_id)
        );
    ");

