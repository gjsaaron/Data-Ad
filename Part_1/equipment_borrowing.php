    //    The seed runs only when all four tables are empty.
    // ------------------------------------------------------------
    $counts = [];
    foreach (['borrowers', 'equipment', 'borrow_transactions', 'borrow_items'] as $table) {
        $counts[$table] = (int) $pdo->query("SELECT COUNT(*) FROM $table")->fetchColumn();
    }

    if ($counts['borrowers'] === 0 &&
        $counts['equipment'] === 0 &&
        $counts['borrow_transactions'] === 0 &&
        $counts['borrow_items'] === 0) {

        $pdo->beginTransaction();

        $borrowerStmt = $pdo->prepare(
