        foreach ($equipmentRows as [$propertyNo, $name, $quantity]) {
            $equipmentStmt->execute([
                ':property_no' => $propertyNo,
                ':equipment_name' => $name,
                ':quantity_available' => $quantity,
            ]);
            $equipmentIds[$propertyNo] = (int) $equipmentStmt->fetchColumn();
