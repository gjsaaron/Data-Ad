        'borrowers' => (int) $pdo->query('SELECT COUNT(*) FROM borrowers')->fetchColumn(),
        'equipment' => (int) $pdo->query('SELECT COUNT(*) FROM equipment')->fetchColumn(),
        'transactions' => (int) $pdo->query('SELECT COUNT(*) FROM borrow_transactions')->fetchColumn(),
        'items' => (int) $pdo->query('SELECT COUNT(*) FROM borrow_items')->fetchColumn(),
    ];

    // Required query 1: simple filter
    $filterQuery = $pdo->query(
        'SELECT property_no, equipment_name, quantity_available
         FROM equipment
         WHERE quantity_available < 5
         ORDER BY quantity_available, equipment_name'
    )->fetchAll();

    // Required query 2: join
    $joinQuery = $pdo->query(
        'SELECT b.borrower_no, b.full_name, bt.borrow_date, bt.status
         FROM borrowers b
         JOIN borrow_transactions bt ON bt.borrower_id = b.borrower_id
         ORDER BY bt.borrow_date'
    )->fetchAll();

    // Required query 3: aggregate
    $aggregateQuery = $pdo->query(
        'SELECT e.equipment_name,
                SUM(bi.quantity) AS total_borrowed,
                COUNT(DISTINCT bi.borrow_id) AS transaction_count
         FROM equipment e
         JOIN borrow_items bi ON bi.equipment_id = e.equipment_id
         GROUP BY e.equipment_id, e.equipment_name
         ORDER BY total_borrowed DESC, e.equipment_name'
    )->fetchAll();

    // Required final join
    $finalJoin = $pdo->query(
        'SELECT b.full_name AS borrower,
                bt.borrow_date,
                e.equipment_name,
                bi.quantity,
                bt.status
         FROM borrow_transactions bt
         JOIN borrowers b ON b.borrower_id = bt.borrower_id
         JOIN borrow_items bi ON bi.borrow_id = bt.borrow_id
         JOIN equipment e ON e.equipment_id = bi.equipment_id
         ORDER BY bt.borrow_date, b.full_name, e.equipment_name'
    )->fetchAll();

} catch (Throwable $e) {
    if ($pdo instanceof PDO && $pdo->inTransaction()) {
        $pdo->rollBack();
    }
    $error = $e->getMessage();
}

