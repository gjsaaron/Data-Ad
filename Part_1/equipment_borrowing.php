         ORDER BY bt.borrow_id'
    )->fetchAll();

    $borrowItems = $pdo->query(
        'SELECT bi.borrow_item_id, bi.borrow_id, e.property_no, e.equipment_name, bi.quantity
         FROM borrow_items bi
         JOIN equipment e ON e.equipment_id = bi.equipment_id
         ORDER BY bi.borrow_item_id'
    )->fetchAll();

